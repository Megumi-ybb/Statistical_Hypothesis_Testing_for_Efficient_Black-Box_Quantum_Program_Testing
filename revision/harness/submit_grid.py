_WORKER_SCRIPT_TEMPLATE = """#!/bin/bash
# Generated by harness/submit_grid.py (--worker script).  CBS grid_run submits
# executable scripts as `./script` (the explicit ./ is mandatory per the grid
# guidelines); this wrapper dispatches to the harness entry points using the
# pinned interpreter behind harness/.venv (a conda-env symlink or a venv).
set -euo pipefail
export ARROW_DEFAULT_MEMORY_POOL=system
# Memory discipline (exit-137 root cause, 2026-07-27): joblib n_jobs=-1 sizes
# its worker pool from the NODE's core count, not the granted slots, and each
# worker maps the whole numpy/scipy/qiskit stack. Cap workers at the granted
# SGE slots and stop per-worker BLAS threading / glibc arena inflation.
export LOKY_MAX_CPU_COUNT="${{NSLOTS:-1}}"
export OMP_NUM_THREADS=1 OPENBLAS_NUM_THREADS=1 MKL_NUM_THREADS=1
export MALLOC_ARENA_MAX=2
cd "$(dirname "$0")"
entry="$1"; shift
case "$entry" in
  runner) exec {python} -c '{bootstrap}' "$@" ;;
  noisy)  exec {python} harness/noisy_grover.py "$@" ;;
  *) echo "grid_worker.sh: unknown entry '$entry' (use runner|noisy)" >&2; exit 2 ;;
esac
"""


def write_worker_script(python: str = DEFAULT_PYTHON) -> Path:
    path = REVISION_DIR / WORKER_SCRIPT_NAME
    path.write_text(_WORKER_SCRIPT_TEMPLATE.format(python=python,
                                                   bootstrap=_INLINE_BOOTSTRAP))
    path.chmod(0o755)
    return path

SCRIPT_CAMPAIGNS: tuple[str, ...] = ("I5",)

DAY_PLAN: dict[str, tuple[str, ...]] = {
    "Day 2": ("I4E1", "I4E1B", "I5", "I8"),
    "Day 3": ("I4E2", "I4E2b", "I4E3", "I9C3", "I7size", "I7seq"),
}


def day_of(campaign: str) -> str:
    for day, names in DAY_PLAN.items():
        if campaign in names:
            return day
    return "unscheduled"




def campaigns_module():
    try:
        from harness import campaigns
    except ImportError:
        return None
    campaigns.register_with_runner()
    return campaigns


def cell_source() -> str:
    return "campaigns" if campaigns_module() is not None else "runner"


def available_campaigns() -> list[str]:
    mod = campaigns_module()
    known = set(runner.CAMPAIGNS) | set(SCRIPT_CAMPAIGNS)
    if mod is not None:
        known |= set(getattr(mod, "CAMPAIGN_ORDER", ()) or getattr(mod, "ENUMERATORS", ()))
    ordered = [c for c in CAMPAIGN_ORDER if c in known]
    return ordered + sorted(known - set(ordered))


def _matches(cell: Cell, circuit: str | None, d: int | None, operator: str | None) -> bool:
    return (
        (circuit is None or cell.circuit == circuit)
        and (d is None or cell.d == d)
        and (operator is None or cell.operator == operator)
    )


def campaign_cells(
    campaign: str,
    *,
    circuit: str | None = None,
    d: int | None = None,
    operator: str | None = None,
    n_reps: int | None = None,
) -> list[Cell]:
    mod = campaigns_module()
    cells: list[Cell] | None = None
    if mod is not None and hasattr(mod, "cells"):
        try:
            cells = list(mod.cells(campaign))
        except (KeyError, ValueError):
            cells = None
    if cells is None:
        if campaign not in runner.CAMPAIGNS:
            raise KeyError(
                f"campaign {campaign!r} is not enumerable yet: it is not in "
                f"runner.CAMPAIGNS ({sorted(runner.CAMPAIGNS)}) and "
                f"harness/campaigns.py {'lacks it' if mod else 'does not exist yet'}"
            )
        cells = runner.enumerate_cells(
            campaign, n_reps=n_reps if n_reps is not None else runner.DEFAULT_N_REPS
        )
    elif n_reps is not None:
        cells = [dataclasses.replace(c, n_reps=n_reps) for c in cells]
    return [c for c in cells if _matches(c, circuit, d, operator)]


def manifest_rows() -> list[dict] | None:
    mod = campaigns_module()
    if mod is None:
        return None
    if hasattr(mod, "manifest_rows"):
        return list(mod.manifest_rows())
    if not hasattr(mod, "manifest"):
        return None
    man = mod.manifest()
    if hasattr(man, "to_dict"):
        return list(man.to_dict(orient="records"))
    if isinstance(man, dict):
        rows = man.get("campaigns")
        if rows is not None:
            return [dict(r) for r in rows]
        return [dict(r, campaign=r.get("campaign", name)) for name, r in man.items()
                if isinstance(r, dict)]
    return [dict(r) for r in man]




@dataclass(frozen=True)
class Job:

    campaign: str
    label: str
    argv: tuple[str, ...]
    n_cells: int
    n_runs: int
    est_core_s: float
    ncpus: int
    mem: str
    out_paths: tuple[str, ...]
    entry_point: str
    entry_verified: bool

    @property
    def est_wall_s(self) -> float:
        return self.est_core_s / max(self.ncpus, 1)

    def command(
        self,
        *,
        grid_run: str = DEFAULT_GRID_RUN,
        grid_submit: str = DEFAULT_GRID_SUBMIT,
        grid_extra: Sequence[str] = (),
    ) -> str:
        parts = [
            grid_run,
            f"--grid_submit={grid_submit}",
            f"--grid_ncpus={self.ncpus}",
            f"--grid_mem={self.mem}",
            *grid_extra,
            *self.argv,
        ]
        return shlex.join(parts)


def sequential_campaigns() -> frozenset[str]:
    mod = campaigns_module()
    return frozenset(getattr(mod, "SEQUENTIAL_CAMPAIGNS", ())) if mod else frozenset()


def _est_core_s(cells: Sequence[Cell], derate: float) -> float:
    sequential = sequential_campaigns()
    total = 0.0
    for cell in cells:
        per_run = PLAN_S_PER_RUN.get(cell.paradigm)
        if per_run is None or cell.campaign in sequential:
            return float("nan")
        total += cell.n_reps * per_run * derate
    return total


def _ncpus_for(n_cells: int, *, forced: int | None, cap: int) -> int:
    if forced is not None:
        return max(1, forced)
    return max(1, min(n_cells, cap))


def _worker_argv(python: str, form: str) -> tuple[list[str], str]:
    if form not in WORKER_FORMS:
        raise ValueError(f"worker form must be one of {WORKER_FORMS}, got {form!r}")
    if form == "script":
        return ["./" + WORKER_SCRIPT_NAME, "runner"], WORKER_SCRIPT_NAME
    if form == "module":
        return [python, "-m", "harness.runner"], "harness/runner.py"
    return [python, "-c", _INLINE_BOOTSTRAP], "harness/runner.py"


def _command_groups(cells: Sequence[Cell]):
    for key, group in runner.iter_jobs(cells):
        selector = {"circuit": key.circuit, "d": key.d, "operator": key.operator}
        yield selector, [key], group


def cell_jobs(
    campaign: str,
    cells: Sequence[Cell],
    *,
    python: str = DEFAULT_PYTHON,
    out_root: str = DEFAULT_OUT_ROOT,
    grid_ncpus: int | None = None,
    ncpus_cap: int = DEFAULT_NCPUS_CAP,
    mem: str = DEFAULT_GRID_MEM,
    derate: float = DEFAULT_DERATE,
    worker_form: str = DEFAULT_WORKER_FORM,
) -> list[Job]:
    prefix, entry = _worker_argv(python, worker_form)
    verified = campaign in runner.CAMPAIGNS
    out_dir = f"{out_root}/{campaign}"
    jobs: list[Job] = []
    for selector, keys, group in _command_groups(cells):
        reps = sorted({c.n_reps for c in group})
        argv = [*prefix, "--campaign", campaign]
        if "circuit" in selector:
            argv += ["--circuit", selector["circuit"]]
        argv += ["--d", str(selector["d"]), "--operator", selector["operator"],
                 "--out", out_dir]
        if len(reps) == 1:
            argv += ["--n-reps", str(reps[0])]
        label = (
            keys[0].filename().removesuffix(".parquet") if len(keys) == 1
            else f"{campaign}__d{selector['d']:02d}__{selector['operator']}"
        )
        jobs.append(
            Job(
                campaign=campaign,
                label=label,
                argv=tuple(argv),
                n_cells=len(group),
                n_runs=runner.total_runs(group),
                est_core_s=_est_core_s(group, derate),
                ncpus=_ncpus_for(len(group), forced=grid_ncpus, cap=ncpus_cap),
                mem=mem,
                out_paths=tuple(f"{out_dir}/{k.filename()}" for k in keys),
                entry_point=entry,
                entry_verified=verified,
            )
        )
    jobs.sort(key=lambda j: (j.campaign, j.label))
    return jobs


def i5_jobs(
    *,
    python: str = DEFAULT_PYTHON,
    out_root: str = DEFAULT_OUT_ROOT,
    n_reps: int | None = None,
    grid_ncpus: int | None = None,
    mem: str = DEFAULT_GRID_MEM,
    circuit: str | None = None,
    d: int | None = None,
    operator: str | None = None,
    worker_form: str = DEFAULT_WORKER_FORM,
) -> list[Job]:
    from harness import noisy_grover as ng

    if circuit not in (None, ng.CIRCUIT) or d not in (None, ng.D):
        return []
    if operator not in (None, ng.BUG_OPERATOR, "baseline"):
        return []

    reps = ng.runner.DEFAULT_N_REPS if n_reps is None else n_reps
    out_dir = f"{out_root}/I5"
    jobs: list[Job] = []
    for arm in ng.ARMS:
        for cfg in ng.noise_configs():
            level = "fake" if cfg.kind == "fake" else cfg.label.removeprefix("aer")
            for m in ng.M_POINTS:
                label = f"I5__arm{arm}__{cfg.label}__m{m:04d}"
                out_path = f"{out_dir}/{label}.parquet"
                prefix = (("./" + WORKER_SCRIPT_NAME, "noisy")
                          if worker_form == "script"
                          else (python, "harness/noisy_grover.py"))
                argv = (
                    *prefix,
                    "--arm",
                    arm,
                    "--strength-level",
                    level,
                    "--m",
                    str(m),
                    "--n-reps",
                    str(reps),
                    "--out",
                    out_path,
                )
                entry = (WORKER_SCRIPT_NAME if worker_form == "script"
                         else "harness/noisy_grover.py")
                jobs.append(
                    Job(
                        campaign="I5",
                        label=label,
                        argv=argv,
                        n_cells=1,
                        n_runs=reps,
                        est_core_s=float("nan"),
                        ncpus=max(1, grid_ncpus or 1),
                        mem=mem,
                        out_paths=(out_path,),
                        entry_point=entry,
                        entry_verified=(REVISION_DIR / entry).exists()
                        and (REVISION_DIR / "harness" / "noisy_grover.py").exists(),
                    )
                )
    jobs.sort(key=lambda j: j.label)
    return jobs


def build_jobs(
    campaigns: Sequence[str],
    *,
    python: str = DEFAULT_PYTHON,
    out_root: str = DEFAULT_OUT_ROOT,
    circuit: str | None = None,
    d: int | None = None,
    operator: str | None = None,
    n_reps: int | None = None,
    grid_ncpus: int | None = None,
    ncpus_cap: int = DEFAULT_NCPUS_CAP,
    mem: str = DEFAULT_GRID_MEM,
    derate: float = DEFAULT_DERATE,
    worker_form: str = DEFAULT_WORKER_FORM,
    skip_existing_root: Path | None = None,
    limit: int | None = None,
) -> tuple[list[Job], list[str]]:
    jobs: list[Job] = []
    notes: list[str] = []
    for campaign in campaigns:
        if campaign in SCRIPT_CAMPAIGNS:
            try:
                jobs += i5_jobs(
                    python=python,
                    out_root=out_root,
                    n_reps=n_reps,
                    grid_ncpus=grid_ncpus,
                    mem=mem,
                    circuit=circuit,
                    d=d,
                    operator=operator,
                    worker_form=worker_form,
                )
            except Exception as exc:
                notes.append(f"{campaign}: skipped ({type(exc).__name__}: {exc})")
            continue
        try:
            cells = campaign_cells(
                campaign, circuit=circuit, d=d, operator=operator, n_reps=n_reps
            )
        except KeyError as exc:
            notes.append(f"{campaign}: skipped ({exc})")
            continue
        if not cells:
            notes.append(f"{campaign}: no cells match the filters")
            continue
        jobs += cell_jobs(
            campaign,
            cells,
            python=python,
            out_root=out_root,
            grid_ncpus=grid_ncpus,
            ncpus_cap=ncpus_cap,
            mem=mem,
            derate=derate,
            worker_form=worker_form,
        )

    order = {name: i for i, name in enumerate(campaigns)}
    jobs.sort(key=lambda j: (order.get(j.campaign, len(order)), j.label))

    if skip_existing_root is not None:
        keep, done = [], 0
        for job in jobs:
            if all((skip_existing_root / p).exists() for p in job.out_paths):
                done += 1
            else:
                keep.append(job)
        if done:
            notes.append(f"--skip-existing: {done:,d} job(s) already have their parquet")
        jobs = keep

    if limit is not None and len(jobs) > limit:
        notes.append(f"--limit {limit}: {len(jobs) - limit:,d} job(s) withheld")
        jobs = jobs[:limit]
    return jobs, notes




def _fmt_hours(seconds: float) -> str:
    if seconds != seconds:
        return "n/a"
    return f"{seconds / 3600:,.1f} h"


def summarise(jobs: Sequence[Job], *, cores: int = 1000) -> list[str]:
    lines = [
        f"{'campaign':<10} {'jobs':>6} {'cells':>8} {'runs':>12} {'core-h':>9} "
        f"{'job wall min/med/max':>24}",
        "-" * 74,
    ]
    by_campaign: dict[str, list[Job]] = {}
    for job in jobs:
        by_campaign.setdefault(job.campaign, []).append(job)

    total_core_s, total_runs, n_unpriced = 0.0, 0, 0
    for campaign, group in by_campaign.items():
        core_s = sum(j.est_core_s for j in group if j.est_core_s == j.est_core_s)
        priced = [j for j in group if j.est_wall_s == j.est_wall_s]
        n_unpriced += len(group) - len(priced)
        if priced:
            walls = sorted(j.est_wall_s for j in priced)
            span = (
                f"{walls[0] / 60:.1f} / {walls[len(walls) // 2] / 60:.1f} / "
                f"{walls[-1] / 60:.1f} min"
            )
        else:
            span = "unpriced"
        runs = sum(j.n_runs for j in group)
        total_core_s += core_s
        total_runs += runs
        lines.append(
            f"{campaign:<10} {len(group):>6,d} {sum(j.n_cells for j in group):>8,d} "
            f"{runs:>12,d} {_fmt_hours(core_s):>9} {span:>24}"
        )

    lines.append("-" * 74)
    lines.append(
        f"{'TOTAL':<10} {len(jobs):>6,d} {sum(j.n_cells for j in jobs):>8,d} "
        f"{total_runs:>12,d} {_fmt_hours(total_core_s):>9}"
    )
    if total_core_s:
        lines.append(
            f"planned wall on {cores:,d} cores at full utilisation: "
            f"{total_core_s / 3600 / cores:.2f} h (queueing and stragglers excluded)"
        )
    if n_unpriced:
        lines.append(
            f"{n_unpriced:,d} job(s) carry no planning figure: I5 is aer-simulator "
            f"bound (time it with the Day-1 sizing step) and sequential campaigns "
            f"{sorted(sequential_campaigns())} are E[N]-driven"
        )
    off_target = [
        j for j in jobs
        if j.est_wall_s == j.est_wall_s
        and not (TARGET_WALL_S[0] <= j.est_wall_s <= TARGET_WALL_S[1])
    ]
    if off_target:
        short = sum(1 for j in off_target if j.est_wall_s < TARGET_WALL_S[0])
        lines.append(
            f"outside the 5-20 min per-job wall target: {len(off_target):,d} "
            f"({short:,d} shorter, {len(off_target) - short:,d} longer) -- tune with "
            f"--ncpus-cap / --grid-ncpus"
        )
    return lines


def script_text(
    jobs: Sequence[Job],
    *,
    workdir: str,
    grid_run: str = DEFAULT_GRID_RUN,
    grid_submit: str = DEFAULT_GRID_SUBMIT,
    grid_extra: Sequence[str] = (),
    sleep_s: float = 0.0,
    argv: Sequence[str] | None = None,
) -> str:
    stamp = _dt.datetime.now(_dt.timezone.utc).isoformat(timespec="seconds")
    out_dirs = sorted({str(Path(p).parent) for job in jobs for p in job.out_paths})
    lines = [
        "#!/usr/bin/env bash",
        f"# generated by harness/submit_grid.py at {stamp}",
        f"# generator argv: {shlex.join(argv) if argv else '(library call)'}",
        f"# cell source: {cell_source()}.py",
        f"# {len(jobs):,d} job(s), {sum(j.n_cells for j in jobs):,d} cells, "
        f"{sum(j.n_runs for j in jobs):,d} runs",
        "#",
        "# Submits from the CLUSTER LOGIN NODE only.  Jobs are idempotent: every cell's",
        "# RNG stream is derived from its identity (runner.seed_master), so re-running a",
        "# job reproduces its parquet exactly.  Retry = re-run the same line.",
        "set -u",
        f'cd "${{REVISION_DIR:-{workdir}}}" || exit 1',
    ]
    lines += [f"mkdir -p {shlex.quote(d)}" for d in out_dirs]
    lines.append("")
    for job in jobs:
        lines.append(f'echo "submitting {job.label} ({job.n_cells} cells, {job.n_runs:,d} runs)"')
        lines.append(
            job.command(grid_run=grid_run, grid_submit=grid_submit, grid_extra=grid_extra)
        )
        if sleep_s > 0:
            lines.append(f"sleep {sleep_s:g}")
    lines.append("")
    return "\n".join(lines)




def _split_campaigns(values: Iterable[str] | None) -> list[str]:
    if not values:
        return available_campaigns()
    out: list[str] = []
    for value in values:
        out += [part.strip() for part in value.split(",") if part.strip()]
    return out


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="python harness/submit_grid.py",
        description="Generate (never submit) the campaign's grid_run job commands.",
        epilog="This script never submits anything; run the emitted script on the cluster.",
    )
    parser.add_argument("--campaign", action="append",
                        help="campaign name; repeatable or comma-separated (default: all)")
    parser.add_argument("--circuit", help="restrict to one circuit (retries)")
    parser.add_argument("--d", type=int, help="restrict to one width (retries)")
    parser.add_argument("--operator", help="restrict to one operator (retries)")
    parser.add_argument("--n-reps", type=int, help="override the campaign's replication count")
    parser.add_argument("--out-root", default=DEFAULT_OUT_ROOT,
                        help=f"result root on the cluster (default {DEFAULT_OUT_ROOT})")
    parser.add_argument("--python", default=DEFAULT_PYTHON,
                        help=f"interpreter used by the jobs (default {DEFAULT_PYTHON})")
    parser.add_argument("--workdir", default=str(REVISION_DIR),
                        help="directory the emitted script cds into (default: this checkout)")
    parser.add_argument("--grid-run", default=DEFAULT_GRID_RUN)
    parser.add_argument("--grid-submit", default=DEFAULT_GRID_SUBMIT)
    parser.add_argument("--grid-ncpus", type=int,
                        help="force per-job cores (default: min(cells in job, --ncpus-cap))")
    parser.add_argument("--ncpus-cap", type=int, default=DEFAULT_NCPUS_CAP,
                        help=f"cap for the automatic per-job core count (default {DEFAULT_NCPUS_CAP})")
    parser.add_argument("--grid-mem", default=DEFAULT_GRID_MEM,
                        help=f"per-job memory request (default {DEFAULT_GRID_MEM})")
    parser.add_argument("--grid-extra", action="append", default=[],
                        help="extra raw grid_run flag, repeatable (site-specific)")
    parser.add_argument("--worker", choices=WORKER_FORMS, default=DEFAULT_WORKER_FORM,
                        help="how the worker is invoked: 'inline' registers campaigns.py "
                             "in-process (correct today), 'module' is the plain "
                             "`python -m harness.runner` form (see WORKER_FORMS)")
    parser.add_argument("--derate", type=float, default=DEFAULT_DERATE,
                        help="grid-core / M3-Max-core slowdown for the estimates "
                             f"(default {DEFAULT_DERATE}; pilot_g4.py measures it)")
    parser.add_argument("--cores", type=int, default=1000,
                        help="grid size used for the wall-clock estimate (default 1000)")
    parser.add_argument("--limit", type=int, help="emit at most N jobs (staged rollout)")
    parser.add_argument("--skip-existing", action="store_true",
                        help="drop jobs whose output parquet already exists under --workdir "
                             "(resume after a partial run)")
    parser.add_argument("--sleep", type=float, default=0.0,
                        help="seconds between submissions in the emitted script")
    parser.add_argument("--emit", type=Path, help="write a submission script instead of printing")
    parser.add_argument("--dry-run", action="store_true", default=True,
                        help="print the commands (default; no submission path exists)")
    parser.add_argument("--print-limit", type=int, default=20,
                        help="commands echoed to stdout when --emit is used (0 = all)")
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    campaigns = _split_campaigns(args.campaign)

    if args.worker == "script":
        write_worker_script(python=args.python)

    jobs, notes = build_jobs(
        campaigns,
        python=args.python,
        out_root=args.out_root,
        circuit=args.circuit,
        d=args.d,
        operator=args.operator,
        n_reps=args.n_reps,
        grid_ncpus=args.grid_ncpus,
        ncpus_cap=args.ncpus_cap,
        mem=args.grid_mem,
        derate=args.derate,
        worker_form=args.worker,
        skip_existing_root=Path(args.workdir) if args.skip_existing else None,
        limit=args.limit,
    )

    print(f"cell source: {cell_source()}.py"
          + ("" if cell_source() == "campaigns" else
             "   (campaigns.py absent: counts are PLAN UPPER BOUNDS, no applicability filter)"))
    for note in notes:
        print(f"note: {note}")
    if args.worker == "script":
        form_note = f"   (CBS grid form: jobs run ./{WORKER_SCRIPT_NAME}, written+chmod +x)"
    elif args.worker == "module":
        form_note = ""
    else:
        form_note = ("   (fallback form: registers campaigns.py in-process instead of "
                     "relying on runner.main(); see WORKER_FORMS)")
    print(f"worker form: {args.worker}{form_note}")
    unverified = sorted({(j.campaign, j.entry_point) for j in jobs if not j.entry_verified})
    for campaign, entry in unverified:
        print(f"note: campaign {campaign} is not registered in runner.CAMPAIGNS, so "
              f"{entry} will reject it -- verify before submitting")

    if not jobs:
        print("no jobs generated", file=sys.stderr)
        return 1

    if args.emit:
        text = script_text(
            jobs,
            workdir=args.workdir,
            grid_run=args.grid_run,
            grid_submit=args.grid_submit,
            grid_extra=args.grid_extra,
            sleep_s=args.sleep,
            argv=list(argv) if argv is not None else sys.argv[1:],
        )
        args.emit.parent.mkdir(parents=True, exist_ok=True)
        args.emit.write_text(text, encoding="utf-8")
        args.emit.chmod(0o755)
        shown = len(jobs) if args.print_limit == 0 else min(args.print_limit, len(jobs))
        for job in jobs[:shown]:
            print(job.command(grid_run=args.grid_run, grid_submit=args.grid_submit,
                              grid_extra=args.grid_extra))
        if shown < len(jobs):
            print(f"... {len(jobs) - shown:,d} more (see {args.emit})")
        print(f"wrote {args.emit} ({len(jobs):,d} jobs) -- NOT submitted; "
              f"run it on the cluster login node")
    else:
        for job in jobs:
            print(job.command(grid_run=args.grid_run, grid_submit=args.grid_submit,
                              grid_extra=args.grid_extra))

    print()
    for line in summarise(jobs, cores=args.cores):
        print(line)
    print(f"estimates use the measured planning figures x --derate {args.derate:g} "
          f"(impl_data.json compute_budget); gate G4 replaces the derating")
    return 0


if __name__ == "__main__":
    sys.exit(main())
